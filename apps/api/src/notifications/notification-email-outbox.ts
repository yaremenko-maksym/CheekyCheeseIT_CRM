/**
 * Два решения очереди писем — чистыми функциями, отдельно от сервиса и крона.
 *
 * Почему отдельно: гейт мутаций не исполняет ни одной интеграционной спеки
 * (`.claude/rules/common/mutation-gate-integration-specs.md`), а ошибиться
 * здесь дороже всего. «Ставить ли письмо» молча теряет единственный канал,
 * доходящий до закрытой вкладки; «на какой адрес» шлёт письмо не тому
 * человеку. Обе функции проверяются юнит-тестом, который гейт видит.
 */
import { isEmailChannelLocked, isNewNotificationType } from '@crm/shared'

/** Потолок попыток. Шестой не будет — строка уходит в `FAILED`. */
export const MAX_EMAIL_ATTEMPTS = 5

/**
 * Сколько ждать перед следующей попыткой после `attempt`-й неудачи.
 *
 * Экспоненциально от минуты с потолком в час. Минута — не догадка: типовой
 * отказ здесь — `429` или пятисотка провайдера, и повтор через секунду
 * означает пять попыток за пять секунд, то есть пять отказов вместо одного.
 * Потолок нужен, чтобы пятая попытка случилась в тот же рабочий день.
 */
export function backoffMs(attempt: number): number {
  const minute = 60_000
  return Math.min(minute * 2 ** (attempt - 1), 60 * minute)
}

/**
 * Ставить ли письмо по этому уведомлению.
 *
 * `prefs` — только ОТЛИЧИЯ от умолчания (в базе хранится лишь то, что человек
 * менял). Отсутствие записи означает «письма идут»: умолчание «выключено»
 * означало бы, что подсистема не работает ни для кого, пока каждый не зайдёт
 * в настройки.
 *
 * Три типа, требующих действия, игнорируют запись целиком — §3: «письма про
 * подтверждения и подписи отключить нельзя… иначе процесс встаёт молча».
 * Разбор запроса такую запись не пропустит, но последний рубеж — здесь: в
 * базу она может попасть и мимо API (руками, миграцией, прежней версией).
 */
export function shouldQueueEmail(type: string, prefs: ReadonlyMap<string, boolean>): boolean {
  // Три старых типа (инвойсы, вакансии) письма не имеют вовсе: ни шаблона, ни
  // настройки. Ставить их в очередь значило бы слать письмо, текста которого
  // никто не писал.
  if (!isNewNotificationType(type)) return false
  if (isEmailChannelLocked(type)) return true
  return prefs.get(type) ?? true
}

export interface AddressRow {
  email: string
  kind: 'WORK' | 'PERSONAL'
}

/**
 * Куда слать: личный адрес, если он есть, иначе рабочий.
 *
 * Личный предпочитается независимо от `verified_at` — спека §5 о личном
 * адресе прямым текстом: «адрес существует, письма на него идут, войти по
 * нему нельзя». Подтверждение открывает ВХОД, а не почту.
 *
 * Цена ошибки в адресе ограничена конструкцией письма: оно не содержит ни
 * сумм, ни процентов, ни имён (§10, `notification-email-copy.ts`), поэтому
 * опечатка раскрывает только сам факт «для вас есть запрос в CRM».
 */
export function pickEmailAddress(rows: readonly AddressRow[]): string | null {
  return (
    rows.find((r) => r.kind === 'PERSONAL')?.email ??
    rows.find((r) => r.kind === 'WORK')?.email ??
    null
  )
}
