import type { LedgerCatalog, LedgerCatalogEntry } from '../ownership/ledger-catalog'
import type {
  LedgerCatalogSnapshot,
  SnapshotDeadline,
  SnapshotHost,
} from '../runtime/production-catalog'
import { type Manifest, type PolicyDeadline, readinessAt } from './manifest'
import { hostPolicyOf } from './manifest.hosts'

/**
 * The run ledger's catalog, built from the manifest (r5 Task 2.5 T3). It lives with the manifest
 * because only manifest code may read manifest data; the ledger depends on the `LedgerCatalog`
 * port, never on this file.
 *
 * Every readiness answer is evaluated at the clock the LEDGER passes in -- the database clock read
 * in the claim transaction (SR-L-21) -- never at a clock of this file's own. The host policy is the
 * manifest's merged policy of the key (`hostPolicyOf`), so a claim cannot be handed a looser one by
 * its caller.
 *
 * !! The manifest is excluded from the production build (`tsconfig.build.json`, `manifest*.ts`), and
 * so is this file. Production reads the GENERATED snapshot instead (T7,
 * `runtime/ledger-catalog.snapshot.ts`, written by `buildLedgerCatalogSnapshot` below).
 */
export function buildLedgerCatalog(manifest: Manifest): LedgerCatalog {
  const entries = new Map<string, LedgerCatalogEntry>()
  for (const t of manifest.types) {
    for (const e of manifest.entries.filter((x) => x.type === t.type)) {
      entries.set(e.id, {
        type: e.type,
        activationFacts: (at) => {
          const r = readinessAt(t, at)
          return {
            readiness: r.status,
            blockerCodes: r.blockers.map((b) => b.code),
            payloadVerified: t.payloadVerified,
          }
        },
        entryReadiness: (at) => readinessAt(e, at).status,
        quotaDeclared: t.quota !== null,
        intervalHours: e.intervalHours,
        floorHours: t.minIntervalHoursFloor,
        banScope: t.banScope,
      })
    }
  }
  return {
    entry: (manifestId) => entries.get(manifestId),
    hostPolicy: (hostKey) => hostPolicyOf(manifest, hostKey),
  }
}

const deadlinesOf = (ds: readonly PolicyDeadline[]): SnapshotDeadline[] =>
  ds.map((d) => ({ kind: d.kind, at: d.at.toISOString() }))

/**
 * T7: the data the production catalog needs, as plain values. Only types that carry an entry are
 * kept, because the catalog resolves entries and nothing else; every host key an entry carries
 * gets its merged policy.
 */
export function buildLedgerCatalogSnapshot(manifest: Manifest): LedgerCatalogSnapshot {
  const entryTypes = new Set(manifest.entries.map((e) => e.type))
  const hostKeys = [...new Set(manifest.entries.map((e) => e.hostKey))].sort()
  return {
    types: manifest.types
      .filter((t) => entryTypes.has(t.type))
      .map((t) => ({
        type: t.type,
        legacy: t.disposition.kind === 'IMPLEMENTED' && t.disposition.contract === 'LEGACY',
        blockerCodes: t.blockers.map((b) => b.code),
        deadlines: deadlinesOf(t.deadlines),
        payloadVerified: t.payloadVerified,
        quotaDeclared: t.quota !== null,
        floorHours: t.minIntervalHoursFloor,
        banScope: t.banScope,
      })),
    entries: manifest.entries.map((e) => ({
      id: e.id,
      type: e.type,
      blockerCodes: e.blockers.map((b) => b.code),
      deadlines: deadlinesOf(e.deadlines),
      intervalHours: e.intervalHours,
    })),
    hosts: hostKeys.flatMap((hostKey): SnapshotHost[] => {
      const policy = hostPolicyOf(manifest, hostKey)
      return policy === undefined ? [] : [{ hostKey, policy }]
    }),
  }
}

/** The committed module's text (prettier normalises the layout; the drift spec compares data). */
export function generateLedgerCatalogSnapshotSource(manifest: Manifest): string {
  return [
    '// GENERATED by `pnpm --filter @crm/api job-sources:manifest:generate` -- do not edit by hand.',
    '// `ledger-catalog.snapshot.drift.spec.ts` fails when this differs from the manifest.',
    "import type { LedgerCatalogSnapshot } from './production-catalog'",
    '',
    `export const LEDGER_CATALOG_SNAPSHOT: LedgerCatalogSnapshot = ${JSON.stringify(buildLedgerCatalogSnapshot(manifest), null, 2)}`,
    '',
  ].join('\n')
}
