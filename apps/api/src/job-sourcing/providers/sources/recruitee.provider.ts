/**
 * Recruitee Careers Site API: `GET https://{tenant}.recruitee.com/api/offers/`
 * (https://docs.recruitee.com/reference/offers). Measurements, captures, robots and terms verdicts:
 * `__fixtures__/recruitee/*.provenance.json` (2026-10-24).
 *
 * THE TENANT IS PART OF THE HOST. `board` is validated as one DNS label (`ats-config.ts`:
 * `DNS_LABEL_PATTERN`), so it cannot add a label, change the registrable domain, carry userinfo or a
 * port, or spell a punycode lookalike; the config is `.strict()`, so there is no field through which
 * a host could be given. Every refusal happens in `parseConfig`, before a request exists.
 *
 * THE `X-Careers-Sites-Token` QUESTION, ANSWERED WITH EVIDENCE (checked 2026-10-24):
 *
 *  - TODAY the endpoint answers WITHOUT the header: bunq 200 (21 offers), tellent 200, an unknown
 *    tenant 404, three requests, none carrying any credential.
 *  - THE DOCUMENTATION says a client "needs to authenticate first" with that header, that the
 *    "Deadline for introducing the token to calls is 10 February 2027" and that "Calls without the
 *    authorization header will return the 401 Unauthorized error"
 *    (https://docs.recruitee.com/reference/authentication-1).
 *  - THE TOKEN IS THE EMPLOYER'S, NOT A KEY WE CAN HOLD: it is generated by a user of the employer's
 *    own Recruitee account ("Careers API token only covers single account's Careers Site API").
 *    A collector that reads other companies' career sites can never obtain one.
 *
 * SO THE SOURCE HAS A SUNSET, AND THE ADAPTER ENFORCES IT: from `RECRUITEE_TOKEN_DEADLINE` on,
 * `collectReport` makes NO request and reports `ACCESS_POLICY` ("KEY_REQUIRED" in the manifest's
 * words), instead of discovering the 401 one tenant at a time. Nothing here ever builds the header,
 * reads a token, or accepts one in a config (a `token` key is an unknown key and the whole config is
 * refused): "no hidden site keys, ever". Before the deadline a 401/403 from a tenant is the loop's
 * `ACCESS_POLICY`, which stops that tenant's run.
 *
 * - ONE REQUEST per attempt: the documentation shows no pagination and the response is the whole
 *   tenant (21 offers = 620 KB for bunq, about 30 KB each, descriptions included). A tenant whose
 *   offers outgrow the transport's 2 MiB cap is refused loudly; see the Greenhouse adapter's note on
 *   why the 10 MiB below is a claim about this file's decoder and not the transport.
 * - NATIVE IDENTITY is `id` (a number; `guid` and `slug` are not stable names for it).
 * - THE POSTING URL IS `careers_url`, taken from the data: bunq's is on its own domain
 *   (`careers.bunq.com/o/{slug}`), so a URL built from the tenant would be wrong.
 * - EMPLOYER: the payload's own per-offer `company_name` (on 21 of 21 bunq offers), else the
 *   config's verified `employer`, else none. Never derived from the tenant.
 * - LOCATION: with several `locations`, each as `city, country` joined "; ", else the single
 *   `location` string the offer carries.
 * - WORKPLACE: `remote` true -> remote; `on_site` or `hybrid` true -> not remote; none of the three
 *   -> unknown.
 * - STATUS: only `published` is an open vacancy; any other status is quarantined as
 *   `NOT_AN_OPEN_VACANCY`. The public endpoint was seen to return published offers only, so this is
 *   a guard on an unseen value, not a measured behaviour.
 * - DATES: `published_at` is PUBLISHED, `updated_at` UPDATED, `close_at` EXPIRY. Recruitee writes
 *   them as `2026-10-15 09:31:36 UTC`, which is not an ISO instant; `recruiteeInstant` rewrites
 *   exactly that shape and nothing else. `created_at` is not mapped (no semantic for it).
 */

export const RECRUITEE_ADAPTER_VERSION = 'recruitee-1'

/** Recruitee's published date from which the Careers Site API answers 401 without a per-company token. */
export const RECRUITEE_TOKEN_DEADLINE = new Date('2027-02-10T00:00:00.000Z')

export const RECRUITEE_LIMITS = {
  maxBytes: 10 * 1024 * 1024,
  maxItemsPerPage: 2_000,
  maxPages: 1,
} as const

const configSchema = atsBoardConfigSchema(RECRUITEE_KIND)
type Config = z.infer<typeof configSchema>

const locationSchema = z.object({
  city: optionalString(200),
  country: optionalString(200),
})

const itemSchema = z.object({
  id: positiveSafeInt(),
  title: boundedString(ORIGINAL_LIMITS.title),
  status: optionalString(50),
  careers_url: urlString(),
  careers_apply_url: urlString().nullish(),
  company_name: optionalString(ORIGINAL_LIMITS.companyName),
  description: optionalString(ORIGINAL_LIMITS.description),
  requirements: optionalString(ORIGINAL_LIMITS.description),
  department: optionalString(200),
  employment_type_code: optionalString(100),
  remote: z.boolean().nullish(),
  on_site: z.boolean().nullish(),
  hybrid: z.boolean().nullish(),
  location: optionalString(ORIGINAL_LIMITS.location),
  locations: z.array(locationSchema).max(100).nullish(),
  tags: z.array(z.unknown()).max(200).nullish(),
  published_at: dateRaw(),
  updated_at: dateRaw(),
  close_at: dateRaw(),
})
type Item = z.infer<typeof itemSchema>

/** `offers` stays OPAQUE so one bad offer is isolated instead of failing the tenant. */
const envelopeSchema = z.object({ offers: z.array(z.unknown()) })
type Envelope = z.infer<typeof envelopeSchema>

const WIRE_INSTANT = /^(\d{4}-\d{2}-\d{2}) (\d{2}:\d{2}:\d{2}) UTC$/

/**
 * `2026-10-15 09:31:36 UTC` -> `2026-10-15T09:31:36Z`. Anything that is not exactly that shape comes
 * back unchanged, so the date policy still judges (and flags) what it cannot read.
 */
export function recruiteeInstant(raw: string | number | null): string | number | null {
  const m = WIRE_INSTANT.exec(String(raw))
  return m === null ? raw : `${m[1]}T${m[2]}Z`
}

/** Remote-ness from the three flags; none set is unknown. */
export function remoteFromFlags(item: {
  remote?: boolean | null | undefined
  on_site?: boolean | null | undefined
  hybrid?: boolean | null | undefined
}): boolean | null {
  if (item.remote === true) return true
  if (item.on_site === true || item.hybrid === true) return false
  return null
}

function locationOf(item: Item): string | null {
  const places = [
    ...new Set(presentStrings(item.locations?.map((l) => placeOf([l.city, l.country])))),
  ]
  if ((item.locations?.length ?? 0) > 1 && places.length > 0) return places.join('; ')
  return nonBlank(item.location)
}

export const recruiteeSpec: ApiJsonSourceSpec<Config, Envelope, Item> = {
  type: 'RECRUITEE_ATS',
  adapterVersion: RECRUITEE_ADAPTER_VERSION,
  configSchema,
  envelopeSchema,
  itemSchema,
  limits: RECRUITEE_LIMITS,
  pageRequest: (config) => ({
    request: {
      url: `https://${config.board}.recruitee.com/api/offers/`,
      headers: { accept: 'application/json' },
    },
    cacheKey: 'offers',
  }),
  extractItems: (envelope) => envelope.offers,
  nextCursor: () => null,
  nativeIdOf: (item) => String(item.id),
  mapItem: (item, config) => ({
    namespace: config.namespace,
    nativeId: String(item.id),
    url: item.careers_url,
    applicationUrl: item.careers_apply_url ?? null,
    title: item.title,
    companyName: nonBlank(item.company_name) ?? config.employer?.name ?? null,
    location: locationOf(item),
    description: [item.description ?? '', item.requirements ?? ''].join(''),
    remote: remoteFromFlags(item),
    employmentType: nonBlank(item.employment_type_code),
    tags: presentStrings([nonBlank(item.department)]).concat(
      presentStrings(item.tags?.map((t) => (typeof t === 'string' ? nonBlank(t) : null))),
    ),
    dates: [
      { raw: recruiteeInstant(item.published_at), contract: 'ISO_ZONED', semantics: 'PUBLISHED' },
      { raw: recruiteeInstant(item.updated_at), contract: 'ISO_ZONED', semantics: 'UPDATED' },
      { raw: recruiteeInstant(item.close_at), contract: 'ISO_ZONED', semantics: 'EXPIRY' },
    ],
    ...(item.status !== null && item.status !== 'published'
      ? { notOpenVacancy: true as const }
      : {}),
  }),
  scopeOf: (config) => ({
    namespace: config.namespace,
    query: null,
    configVersion: config.configVersion,
    window: null,
  }),
}

/**
 * The attempt that is not made: from the deadline on, every tenant needs a token no third party can
 * hold. ONE report, `ACCESS_POLICY`, at the unbuilt-request address, so nothing about a request
 * (no host, no tenant) is claimed for a request that never existed; `ERROR` with no page, so the
 * batch is FAILED and cannot claim any coverage.
 */
function refuseWithoutToken(config: Config, ctx: CollectionContext): CollectionBatch {
  const at = ctx.now()
  return buildCollectionBatch({
    observations: [],
    facts: {
      stop: 'ERROR',
      pagesCompleted: 0,
      counts: { raw: 0, normalized: 0, invalid: 0, quarantined: 0, discarded: 0 },
      scope: recruiteeSpec.scopeOf(config, at),
      // Stryker disable next-line BooleanLiteral: this batch is FAILED, and a non-SUCCEEDED attempt has PARTIAL coverage whatever `resumed` says (`deriveCoverage`), so the flag cannot be seen in the result.
      resumed: false,
    },
    requests: [
      buildRequestReport(
        {
          attempt: 1,
          page: 1,
          url: UNBUILT_REQUEST_URL,
          status: null,
          startedAt: at,
          endedAt: at,
          cost: null,
          error: {
            code: 'ACCESS_POLICY',
            message: `from ${RECRUITEE_TOKEN_DEADLINE.toISOString().slice(0, 10)} the Careers Site API requires the employer's own credentials, this collector holds none and made no request`,
          },
        },
        ctx.secrets,
      ),
    ],
    checkpoint: null,
    invalidSamples: [],
  })
}

export const recruiteeProvider = definePagedProvider(recruiteeSpec, (config, ctx) =>
  ctx.now().getTime() >= RECRUITEE_TOKEN_DEADLINE.getTime()
    ? Promise.resolve(refuseWithoutToken(config, ctx))
    : collectJsonPages(recruiteeSpec, config, ctx),
)
