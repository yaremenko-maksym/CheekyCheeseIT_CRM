/**
 * Экранирование текста, попадающего в HTML письма.
 *
 * Существовал двумя посимвольно одинаковыми копиями — в `ContactService`
 * (сообщение посетителя формы) и в `PersonalEmailInviteMailerService` (имя,
 * введённое админом). Позиция 7a добавила третьего потребителя (письма
 * уведомлений), и третья копия сделала бы расхождение вопросом времени:
 * достаточно, чтобы одна из них однажды забыла апостроф, и знать об этом
 * будет только почтовый клиент получателя.
 *
 * Порядок замен значим: `&` идёт ПЕРВЫМ, иначе уже вставленные `&lt;`
 * экранируются повторно и читатель видит `&amp;lt;`.
 */
export function escapeHtml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;')
}
