/**
 * Экранирование текста, попадающего в HTML письма.
 *
 * Существовал двумя посимвольно одинаковыми копиями — в `ContactService`
 * (сообщение посетителя формы) и в `PersonalEmailInviteMailerService` (имя,
 * введённое админом). Позиция 7a добавила третьего потребителя (письма
 * уведомлений), и третья копия сделала бы расхождение вопросом времени:
 * достаточно, чтобы одна из них однажды забыла апостроф, и знать об этом
 * будет только почтовый клиент получателя.
 *
 * Порядок замен значим: `&` идёт ПЕРВЫМ, иначе уже вставленные `&lt;`
 * экранируются повторно и читатель видит `&amp;lt;`.
 */
declare const escapedHtmlBrand: unique symbol

/**
 * Строка, безопасная для вставки в HTML письма без дальнейшего
 * экранирования — либо потому что прошла через `escapeHtml`, либо потому что
 * автор явно поручился за неё через `trustedHtml`.
 *
 * Заведён вместо простого `string` в `EmailBlock.html` / `EmailLayoutInput.footer`
 * (SR-L-8, security-review PR #673 круг 2): до этой правки хелпер принимал
 * сырую строку, и промах третьего вызывающего (забытый `escapeHtml` на
 * пользовательских данных) был бы тихим — компилятор его не видел, а
 * почтовый клиент получателя увидел бы первым. Бренд делает «забыл
 * экранировать» ошибкой типов, а не инцидентом.
 */
export type EscapedHtml = string & { readonly [escapedHtmlBrand]: true }

export function escapeHtml(value: string): EscapedHtml {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;') as EscapedHtml
}

/**
 * Пометить строку как уже безопасную для HTML — БЕЗ прогона через
 * `escapeHtml`.
 *
 * Только для литеральной разметки, которую пишет разработчик в коде самого
 * письма (кнопка, `<strong>` в защитной оговорке приглашения, статичные
 * строки тела) — НИКОГДА для строки, пришедшей из запроса, базы или
 * подстановки пользовательских данных: для них есть `escapeHtml`, и его
 * пропуск компилятор с этой правки не пропускает молча (SR-L-8).
 */
export function trustedHtml(value: string): EscapedHtml {
  return value as EscapedHtml
}

/**
 * Предложение с одной выделенной фразой: `phrase` оборачивается в `<strong>`
 * при ПЕРВОМ вхождении, и текст вокруг, и сама фраза экранируются
 * (`escapeHtml`) — разметку добавляет только этот хелпер.
 *
 * Зачем он, а не «два сообщения каталога по обе стороны тега»: порядок слов
 * в uk и en разный, и предложение, разрезанное на фрагменты, зафиксировало бы
 * один порядок для обоих языков. Здесь предложение рендерится целиком, а
 * фраза — известное сообщение каталога, поэтому её поиск в готовой строке
 * детерминирован.
 *
 * Фраза не найдена (или пустая) — экранированное предложение без тега, без
 * исключения: письмо с невыделенной оговоркой лучше письма, которое не ушло.
 */
export function emphasize(sentence: string, phrase: string): EscapedHtml {
  const at = phrase === '' ? -1 : sentence.indexOf(phrase)
  if (at === -1) return escapeHtml(sentence)
  const before = escapeHtml(sentence.slice(0, at))
  const middle = escapeHtml(phrase)
  const after = escapeHtml(sentence.slice(at + phrase.length))
  return trustedHtml(`${before}<strong>${middle}</strong>${after}`)
}
