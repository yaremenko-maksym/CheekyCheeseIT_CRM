/**
 * Убрать переводы строк из значения, которое уезжает в ЗАГОЛОВОК письма.
 *
 * Вынесено из `contact.service.ts` (где этот контроль появился первым и с
 * обоснованием) в общий модуль, когда понадобился второму отправителю —
 * письмам уведомлений (SR-M-1, security-review PR #673 круг 1). Рядом с
 * `escape-html.ts` и по той же причине: контроль, который обязаны наследовать
 * все, кто шлёт почту, не может жить приватной функцией одного сервиса.
 *
 * **Зачем, если Resend принимает JSON, а не сырой SMTP.** Провайдер собирает
 * MIME сам, и доказать инъекцию через его API мы не берёмся. Но `\r\n` внутри
 * строки JSON — это ровно то, из чего заголовок собирается на той стороне, и
 * подсунуть туда лишнюю строку, похожую на заголовок, дешевле, чем доказывать,
 * что нельзя. Формулировка `contact.service.ts` дословно: «defense against
 * header-injection even though Resend's API is JSON (not raw SMTP)».
 *
 * Применяется к `subject` и `reply_to` — и НЕ применяется к телу письма: там
 * перевод строки законен (text-версия из него и состоит) и безвреден.
 *
 * Схлопывает подряд идущие переводы в ОДИН пробел и обрезает края: тема,
 * склеенная в «Проект  Bcc: …», читалась бы как тема с двойным пробелом, а не
 * как заголовок.
 */
export function stripCrlf(value: string): string {
  return value.replace(/[\r\n]+/g, ' ').trim()
}
