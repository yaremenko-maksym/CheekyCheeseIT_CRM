import { describe, expect, it } from 'vitest'
import { stripCrlf } from './strip-crlf'

/**
 * Страж контроля, который защищает ЗАГОЛОВОК письма (SR-M-1).
 *
 * Функция переехала из `contact.service.ts` в общий модуль, когда её
 * понадобилось применить второму отправителю. Переезд без теста означал бы,
 * что поведение держится только на вызывающих, — а у одного из них (письма
 * уведомлений) подстановка приходит из пользовательского ввода, где перевод
 * строки разрешён валидацией (`z.string().max(255)`).
 */
describe('stripCrlf', () => {
  it('склеивает подсунутый заголовок в одну строку', () => {
    // Ровно та подстановка, которой заказан контроль: имя проекта с переводом
    // строки и похожим на заголовок продолжением.
    expect(stripCrlf('Проект\r\nBcc: attacker@example.com')).toBe(
      'Проект Bcc: attacker@example.com',
    )
  })

  it('одиночный перевод строки тоже убирается', () => {
    // `\n` без `\r` — то, что даёт обычная форма в браузере.
    expect(stripCrlf('Проект\nBcc: attacker@example.com')).toBe('Проект Bcc: attacker@example.com')
  })

  it('подряд идущие переводы становятся ОДНИМ пробелом', () => {
    // Иначе тема получала бы дыру из пробелов там, где была пустая строка.
    expect(stripCrlf('Проект\r\n\r\n\nещё')).toBe('Проект ещё')
  })

  it('края обрезаются', () => {
    expect(stripCrlf('\r\n Проект \n')).toBe('Проект')
  })

  it('строку без переводов не трогает', () => {
    // Кроме краёв: значение, которое и так годится в заголовок, обязано
    // доехать до него дословно.
    expect(stripCrlf('Запрос на подпись контракта')).toBe('Запрос на подпись контракта')
  })

  it('табуляцию не считает переводом строки', () => {
    // Заголовок ломает именно перевод строки. Расширять запрет на любой
    // пробельный символ значило бы менять видимый текст темы без причины.
    expect(stripCrlf('Проект\tОдин')).toBe('Проект\tОдин')
  })
})
